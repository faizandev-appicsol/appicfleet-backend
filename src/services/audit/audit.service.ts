export type AuditEventInput = {
  action: AuditAction
  entityType: string
  entityId?: string
  actorUserId?: string
  organizationId?: string | null
  branchId?: string
  result?: AuditResult
  /** Descriptive context only. Credential-like keys are stripped before saving. */
  metadata?: Record<string, unknown>
  meta?: RequestMeta
}

const SECRET_KEY_PATTERN =
  /pass(word|phrase)?|secret|token|authorization|cookie|api[-_]?key|credential|hash|otp|pin$|private[-_]?key/i
const REDACTED = '[REDACTED]'
const MAX_DEPTH = 4
const MAX_STRING_LENGTH = 500
const MAX_ARRAY_LENGTH = 50

function sanitizeValue(value: unknown, depth: number): unknown {
  if (value === null || value === undefined) return value
  if (typeof value === 'string') {
    return value.length > MAX_STRING_LENGTH ? `${value.slice(0, MAX_STRING_LENGTH)}…` : value
  }
  if (typeof value === 'number' || typeof value === 'boolean') return value
  if (value instanceof Date) return value.toISOString()
  if (depth >= MAX_DEPTH) return '[TRUNCATED]'
  if (Array.isArray(value)) {
    return value.slice(0, MAX_ARRAY_LENGTH).map((item) => sanitizeValue(item, depth + 1))
  }
  if (typeof value === 'object') return sanitizeMetadata(value as Record<string, unknown>, depth + 1)
  return undefined
}

/** Drops credential-like keys (password, token, secret, hash, ...) recursively. */
export function sanitizeMetadata(
  metadata: Record<string, unknown>,
  depth = 0,
): Record<string, unknown> {
  const result: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(metadata)) {
    if (SECRET_KEY_PATTERN.test(key)) {
      result[key] = REDACTED
      continue
    }
    const sanitized = sanitizeValue(value, depth)
    if (sanitized !== undefined) result[key] = sanitized
  }
  return result
}

/**
 * Persists an audit event. It never throws: a failing audit write must not break the request,
 * so errors are logged (name only) and swallowed.
 */
export async function recordAuditEvent(input: AuditEventInput): Promise<void> {
  try {
    await insertAuditEvent({
      actorUserId: input.actorUserId,
      action: input.action,
      entityType: input.entityType,
      entityId: input.entityId,
      organizationId: input.organizationId ?? undefined,
      branchId: input.branchId,
      requestId: input.meta?.requestId,
      correlationId: input.meta?.correlationId,
      result: input.result ?? 'success',
      metadata: sanitizeMetadata(input.metadata ?? {}),
      ip: input.meta?.ip,
      userAgent: input.meta?.userAgent?.slice(0, 256),
    })
  } catch (error) {
    logger.error('Audit event could not be recorded', {
      module: 'audit',
      action: input.action,
      name: error instanceof Error ? error.name : 'Error',
    })
  }
}
