/**
 * Whether the default grants of a stored role include the permission.
 * Legacy aliases (`users:read`, `users:write`) are expanded; every expanded key must be held.
 * Unknown roles are denied.
 */
export function roleHasPermission(role: Role, permission: PermissionInput): boolean {
  const grants = SYSTEM_ROLE_PERMISSIONS[role] as readonly Permission[] | undefined
  if (!grants) return false
  return expandPermission(permission).every((key) => grants.includes(key))
}
