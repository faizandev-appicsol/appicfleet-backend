/**
 * Primary role codes as stored in `users.role` (DB enum, unchanged for existing data).
 *
 * Module 3 system role codes and how they map onto the stored enum:
 *   SUPER_ADMIN     -> SUPER_ADMIN   (new; platform operator, accessAllOrganizations)
 *   ORG_ADMIN       -> ADMIN         (ORG_ADMIN ≈ ADMIN)
 *   BRANCH_MANAGER  -> MANAGER       (BRANCH_MANAGER ≈ MANAGER)
 *   STANDARD_USER   -> USER          (STANDARD_USER ≈ USER)
 * DISPATCHER and VIEWER remain as additional system roles with profile-only defaults.
 *
 * Authorization decisions are made on permissions, never on these names.
 */
export const ROLES = {
  SUPER_ADMIN: 'SUPER_ADMIN',
  ADMIN: 'ADMIN',
  MANAGER: 'MANAGER',
  DISPATCHER: 'DISPATCHER',
  VIEWER: 'VIEWER',
  USER: 'USER',
  INVESTOR: 'INVESTOR',
} as const

export type Role = (typeof ROLES)[keyof typeof ROLES]

/** Canonical Module 3 system role codes used by `roles.code` documents. */
export const SYSTEM_ROLE_CODES = {
  SUPER_ADMIN: 'SUPER_ADMIN',
  ORG_ADMIN: 'ORG_ADMIN',
  BRANCH_MANAGER: 'BRANCH_MANAGER',
  STANDARD_USER: 'STANDARD_USER',
  DISPATCHER: 'DISPATCHER',
  VIEWER: 'VIEWER',
  INVESTOR: 'INVESTOR',
} as const

export type SystemRoleCode = (typeof SYSTEM_ROLE_CODES)[keyof typeof SYSTEM_ROLE_CODES]

const ROLE_TO_SYSTEM_CODE: Record<Role, SystemRoleCode> = {
  [ROLES.SUPER_ADMIN]: SYSTEM_ROLE_CODES.SUPER_ADMIN,
  [ROLES.ADMIN]: SYSTEM_ROLE_CODES.ORG_ADMIN,
  [ROLES.MANAGER]: SYSTEM_ROLE_CODES.BRANCH_MANAGER,
  [ROLES.DISPATCHER]: SYSTEM_ROLE_CODES.DISPATCHER,
  [ROLES.VIEWER]: SYSTEM_ROLE_CODES.VIEWER,
  [ROLES.USER]: SYSTEM_ROLE_CODES.STANDARD_USER,
  [ROLES.INVESTOR]: SYSTEM_ROLE_CODES.INVESTOR,
}

/** Maps a stored role to the canonical system role code (ADMIN -> ORG_ADMIN, etc.). */
export function toSystemRoleCode(role: Role): SystemRoleCode {
  return ROLE_TO_SYSTEM_CODE[role]
}

const SYSTEM_CODE_SET: ReadonlySet<string> = new Set(Object.values(SYSTEM_ROLE_CODES))

export function isSystemRoleCode(value: string): boolean {
  return SYSTEM_CODE_SET.has(value.toUpperCase()) || isRole(value.toUpperCase())
}

/**
 * Stored account statuses.
 * Module 3 statuses: ACTIVE, INACTIVE, SUSPENDED. INVITED belongs to the invite flow.
 * DISABLED is a legacy alias of INACTIVE: old documents may still carry it, reads normalize it
 * to INACTIVE, and nothing writes it any more.
 */
export const USER_STATUSES = {
  ACTIVE: 'ACTIVE',
  INACTIVE: 'INACTIVE',
  SUSPENDED: 'SUSPENDED',
  INVITED: 'INVITED',
  DISABLED: 'DISABLED',
} as const

export type UserStatus = (typeof USER_STATUSES)[keyof typeof USER_STATUSES]

/** Maps the legacy DISABLED status to INACTIVE; every other status is returned unchanged. */
export function normalizeUserStatus(status: UserStatus): Exclude<UserStatus, 'DISABLED'> {
  return status === USER_STATUSES.DISABLED ? USER_STATUSES.INACTIVE : status
}

/** Status used by organizations, legal entities, branches and roles. */
export const ENTITY_STATUSES = {
  ACTIVE: 'ACTIVE',
  INACTIVE: 'INACTIVE',
} as const

export type EntityStatus = (typeof ENTITY_STATUSES)[keyof typeof ENTITY_STATUSES]

const PUBLIC_ROLES = {
  super_admin: ROLES.SUPER_ADMIN,
  admin: ROLES.ADMIN,
  manager: ROLES.MANAGER,
  dispatcher: ROLES.DISPATCHER,
  viewer: ROLES.VIEWER,
  user: ROLES.USER,
  investor: ROLES.INVESTOR,
} as const

/** Extra spellings accepted on input only (Module 3 system role names). */
const ROLE_INPUT_ALIASES: Record<string, Role> = {
  org_admin: ROLES.ADMIN,
  branch_manager: ROLES.MANAGER,
  standard_user: ROLES.USER,
}

const PUBLIC_STATUSES = {
  active: USER_STATUSES.ACTIVE,
  inactive: USER_STATUSES.INACTIVE,
  suspended: USER_STATUSES.SUSPENDED,
  invited: USER_STATUSES.INVITED,
  // Input alias for clients written before Module 3.
  disabled: USER_STATUSES.INACTIVE,
} as const

export type PublicRole = keyof typeof PUBLIC_ROLES
export type PublicStatus = Exclude<keyof typeof PUBLIC_STATUSES, 'disabled'>

export function isPublicRole(value: string): value is PublicRole {
  return value in PUBLIC_ROLES
}

export function isPublicStatus(value: string): value is keyof typeof PUBLIC_STATUSES {
  return value in PUBLIC_STATUSES
}

export function toRole(value: string): Role | null {
  if (isPublicRole(value)) return PUBLIC_ROLES[value]
  return ROLE_INPUT_ALIASES[value] ?? null
}

/** Parses a public status (including the `disabled` alias, which becomes INACTIVE). */
export function toStatus(value: string): UserStatus | null {
  return isPublicStatus(value) ? PUBLIC_STATUSES[value] : null
}

export function isRole(value: string): value is Role {
  return Object.values(ROLES).some((role) => role === value)
}

export function isUserStatus(value: string): value is UserStatus {
  return Object.values(USER_STATUSES).some((status) => status === value)
}

export function toPublicRole(role: Role): PublicRole {
  return role.toLowerCase() as PublicRole
}

export function toPublicStatus(status: UserStatus): PublicStatus {
  return normalizeUserStatus(status).toLowerCase() as PublicStatus
}

