export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS]

/**
 * Pre-Module-3 permission keys. Kept only so existing call sites and tokens keep working
 * during the transition. They are never stored and never granted directly; they expand to
 * the dotted keys below. Prefer the dotted keys in new code.
 */
export const LEGACY_PERMISSIONS = {
  /** @deprecated use PERMISSIONS.USERS_VIEW */
  USERS_READ: 'users:read',
  /** @deprecated use USERS_CREATE + USERS_UPDATE + USERS_DEACTIVATE */
  USERS_WRITE: 'users:write',
} as const

export type LegacyPermission = (typeof LEGACY_PERMISSIONS)[keyof typeof LEGACY_PERMISSIONS]

/** Anything `hasPermission` / `requirePermission` accepts. */
export type PermissionInput = Permission | LegacyPermission

const LEGACY_EXPANSION: Record<LegacyPermission, readonly Permission[]> = {
  [LEGACY_PERMISSIONS.USERS_READ]: [PERMISSIONS.USERS_VIEW],
  // `users:write` implied create, update and delete, so every one of them must be held.
  [LEGACY_PERMISSIONS.USERS_WRITE]: [
    PERMISSIONS.USERS_CREATE,
    PERMISSIONS.USERS_UPDATE,
    PERMISSIONS.USERS_DEACTIVATE,
  ],
}

export const ALL_PERMISSIONS: readonly Permission[] = Object.values(PERMISSIONS)

const PERMISSION_SET: ReadonlySet<string> = new Set(ALL_PERMISSIONS)

export function isPermission(value: string): value is Permission {
  return PERMISSION_SET.has(value)
}

export function isLegacyPermission(value: string): value is LegacyPermission {
  return value in LEGACY_EXPANSION
}

/** Resolves a requested permission (dotted or legacy alias) to the dotted keys that must all be held. */
export function expandPermission(permission: PermissionInput): readonly Permission[] {
  if (isLegacyPermission(permission)) return LEGACY_EXPANSION[permission]
  return [permission]
}

